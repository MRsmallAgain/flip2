#!/usr/bin/env bash
# Mirror pinned catalog binaries to the wizard S3 bucket under packages/
# so flip2burn.online can fetch them same-origin (no CORS).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
CATALOG="$ROOT/wizard/catalog.json"
SOURCES="$ROOT/pipeline/deploy/sources"
DIST="$ROOT/pipeline/deploy/dist"
STACK="${FLIP2_SITE_STACK:-flip2burn-site}"
REGION="${FLIP2_SITE_REGION:-us-east-1}"
WORK="${FLIP2_PACKAGES_WORK:-$ROOT/.flip2-site-packages}"

die() { echo "$*" >&2; exit 1; }

command -v aws >/dev/null || die "aws CLI not found"
command -v curl >/dev/null || die "curl not found"
command -v jq >/dev/null || die "jq not found"
command -v sha256sum >/dev/null || die "sha256sum not found"

DRY=0
ONLY_ID=""
while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1; shift ;;
    --only)
      ONLY_ID="${2:-}"
      shift 2
      ;;
    -h|--help)
      cat <<'EOF'
Usage: sync-site-packages.sh [--dry-run] [--only CATALOG_ID]

Ensure wizard/catalog.json artifacts exist under s3://<bucket>/packages/<file>
with sha256 verified locally before upload.

  --only ID   Sync one catalog entry (e.g. companion-win). Skips neutron and installers.

Env: FLIP2_SITE_STACK, FLIP2_SITE_REGION, FLIP2_PACKAGES_WORK
EOF
      exit 0
      ;;
    *) die "Unknown: $1" ;;
  esac
done

BUCKET="$(aws cloudformation describe-stacks --region "$REGION" \
  --stack-name "$STACK" \
  --query "Stacks[0].Outputs[?OutputKey=='BucketName'].OutputValue" --output text 2>/dev/null || true)"
[[ -n "$BUCKET" && "$BUCKET" != "None" ]] || die "Stack $STACK missing BucketName (region $REGION)"

mkdir -p "$WORK"

local_path() {
  local file="$1" sha="$2" size="$3" p="" got size_got
  if [[ -f "$DIST/$file" ]]; then
    p="$DIST/$file"
  elif [[ -f "$ROOT/companion/dist/$file" ]]; then
    p="$ROOT/companion/dist/$file"
  elif [[ -f "$SOURCES/$file" ]]; then
    p="$SOURCES/$file"
  elif [[ -f "$WORK/$file" ]]; then
    p="$WORK/$file"
  fi
  if [[ -n "$p" ]]; then
    got="$(sha256sum "$p" | awk '{print $1}')"
    size_got="$(stat -c%s "$p")"
    if [[ "$got" == "$sha" && "$size_got" == "$size" ]]; then
      echo "$p"
      return 0
    fi
  fi
  echo ""
}

fetch_verify() {
  local file="$1" url="$2" sha="$3" size="$4" out="$WORK/$file" got size_got
  echo "==> fetch: $file" >&2
  curl -fsSL -o "$out" "$url"
  got="$(sha256sum "$out" | awk '{print $1}')"
  size_got="$(stat -c%s "$out")"
  [[ "$got" == "$sha" ]] || { echo "BAD sha256 for $file" >&2; return 1; }
  [[ "$size_got" == "$size" ]] || { echo "BAD size for $file" >&2; return 1; }
  echo "$out"
}

need_upload() {
  local file="$1" size="$2" sha="$3" key="packages/$file" meta len stamped
  meta="$(aws s3api head-object --bucket "$BUCKET" --key "$key" 2>/dev/null || true)"
  [[ -z "$meta" ]] && return 0
  len="$(echo "$meta" | jq -r '.ContentLength // 0')"
  [[ "$len" == "$size" ]] || return 0
  # Size alone is not identity: a rebuilt asset can land on exactly the previous
  # byte count (the v1.4.0-alpha.5 clean/image-post zips and SHA256SUMS did) and
  # was then skipped as already-present, leaving old bytes behind a new pin.
  # Compare the sha256 stamped into object metadata at upload instead. An object
  # with no stamp predates this check and is re-uploaded once to acquire one.
  stamped="$(echo "$meta" | jq -r '.Metadata.sha256 // ""')"
  [[ "$stamped" == "$sha" ]] && return 1
  return 0
}

catalog_rows() {
  if [[ -n "$ONLY_ID" ]]; then
    jq -r --arg id "$ONLY_ID" '.files[] | select(.id == $id) | [.id, .file, (.url // ""), .sha256, .size] | @tsv' "$CATALOG"
  else
    jq -r '.files[] | [.id, .file, (.url // ""), .sha256, .size] | @tsv' "$CATALOG"
  fi
}

while IFS=$'\t' read -r id file url sha size; do
  [[ -n "$file" && -n "$sha" && -n "$size" ]] || continue
  path="$(local_path "$file" "$sha" "$size" || true)"
  if [[ -z "$path" ]]; then
    if [[ -z "$url" || "$url" == "null" ]]; then
      bouncy_src="$SOURCES/com.dozingcatsoftware.bouncy_43.apk"
      if [[ -f "$bouncy_src" ]]; then
        got="$(sha256sum "$bouncy_src" | awk '{print $1}')"
        if [[ "$got" == "$sha" ]]; then
          cp -f "$bouncy_src" "$WORK/$file"
          path="$WORK/$file"
        fi
      fi
      if [[ -z "$path" ]]; then
        echo "skip (no url, no local pin): $id / $file" >&2
        continue
      fi
    else
      path="$(fetch_verify "$file" "$url" "$sha" "$size")" || die "fetch failed: $id"
    fi
  fi

  if [[ "$DRY" -eq 1 ]]; then
    echo "would upload: $path -> s3://$BUCKET/packages/$file"
    continue
  fi

  if need_upload "$file" "$size" "$sha"; then
    echo "==> s3 cp: packages/$file"
    aws s3 cp "$path" "s3://${BUCKET}/packages/$file" \
      --content-type "application/octet-stream" \
      --cache-control "public,max-age=86400" \
      --metadata "sha256=$sha"
  else
    echo "skip (s3 ok): packages/$file"
  fi
done < <(catalog_rows)

echo "==> site packages sync done (bucket $BUCKET)"
