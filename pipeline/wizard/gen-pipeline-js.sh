#!/usr/bin/env bash
# Regenerate push-manifest.json from pipeline/deploy/manifest.json (A4).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
MANIFEST="$ROOT/pipeline/deploy/manifest.json"
OUT="$ROOT/pipeline/wizard/push-manifest.json"

command -v jq >/dev/null || { echo "jq not found" >&2; exit 1; }

wizard_incoming() {
  case "$1" in
    forkgram) echo forkgram.apk ;;
    materialfiles) echo materialfiles.apk ;;
    launcher4) echo launcher4.apk ;;
    ime) echo nullkeyboard.apk ;;
    intertune) echo intertune.apk ;;
    bouncy) echo bouncy.apk ;;
    *) jq -r --arg n "$1" '.components[] | select(.name==$n) | .incoming // empty' "$MANIFEST" ;;
  esac
}

mapfile -t MOD_PATHS < <(jq -r '
  .components[]
  | select([.tiers[]] | index("full"))
  | select(.artifact == "magisk-module" and .name != "tagdrawer")
  | "payload/modules/" + (.zip | split("/") | last)
' "$MANIFEST")

TAG_PATH="$(jq -r '
  .components[] | select(.name=="tagdrawer") | "payload/modules/" + (.zip | split("/") | last)
' "$MANIFEST")"

mapfile -t APK_PATHS < <(jq -r '
  .components[]
  | select([.tiers[]] | index("full"))
  | select(.artifact == "user-apk" and (.apk // "") != "")
  | "payload/apks/" + (.apk | split("/") | last)
' "$MANIFEST")

REQUIRED=()
for p in "${MOD_PATHS[@]}"; do REQUIRED+=("$(basename "$p")"); done
REQUIRED+=("$(basename "$TAG_PATH")")
for p in "${APK_PATHS[@]}"; do REQUIRED+=("$(basename "$p")"); done

while IFS=$'\t' read -r name _pkg; do
  [[ -n "$name" ]] || continue
  inc="$(wizard_incoming "$name")"
  [[ -n "$inc" ]] && REQUIRED+=("$inc")
done < <(jq -r '
  .components[]
  | select([.tiers[]] | index("full") or index("wizard"))
  | select(.artifact == "user-apk" and (.incoming // "") != "" and (.apk // "") == "")
  | [.name, .package] | @tsv
' "$MANIFEST")

REQUIRED+=("ggml-tiny-q5_1.bin" "vosk-model-small-en-us-0.15.zip" "vosk-model-small-uk-v3-nano.zip")

jq -n \
  --argjson mod "$(printf '%s\n' "${MOD_PATHS[@]}" | jq -R . | jq -s .)" \
  --argjson apk "$(printf '%s\n' "${APK_PATHS[@]}" | jq -R . | jq -s .)" \
  --arg td "$TAG_PATH" \
  --argjson req "$(printf '%s\n' "${REQUIRED[@]}" | jq -R . | jq -s .)" \
  '{
    "$comment": "Generated by pipeline/wizard/gen-pipeline-js.sh — do not hand-edit.",
    installerModulePaths: $mod,
    installerApkPaths: $apk,
    tagDrawerModulePath: $td,
    tagDrawerApkEntry: "system/app/PixelTagDrawer/PixelTagDrawer.apk",
    wallpaperPath: "payload/wallpaper/flip2-wallpaper.png",
    catalogRenames: {
      "forkgram": "forkgram.apk",
      "intertune": "intertune.apk",
      "bouncy": "bouncy.apk",
      "materialfiles": "materialfiles.apk",
      "whisper-tiny": "ggml-tiny-q5_1.bin",
      "vosk-en": "vosk-model-small-en-us-0.15.zip",
      "vosk-uk": "vosk-model-small-uk-v3-nano.zip"
    },
    requiredIncoming: $req
  }' > "$OUT"

echo "generated: $OUT"
