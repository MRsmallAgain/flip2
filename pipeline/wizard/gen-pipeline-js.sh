#!/usr/bin/env bash
# Regenerate push-manifest.json from pipeline/deploy/manifest.json (A4).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
MANIFEST="$ROOT/pipeline/deploy/manifest.json"
OUT="$ROOT/pipeline/wizard/push-manifest.json"
JS_OUT="$ROOT/wizard/pages/js/push-manifest.js"
OUT_SLIM="$ROOT/pipeline/wizard/push-manifest-slim.json"
JS_OUT_SLIM="$ROOT/wizard/pages/js/push-manifest-slim.js"
SOURCES="$ROOT/pipeline/deploy/sources"

command -v jq >/dev/null || { echo "jq not found" >&2; exit 1; }
# shellcheck source=/dev/null
source "$ROOT/pipeline/deploy/wizard-apk-basename.sh"

mapfile -t MOD_PATHS < <(jq -r '
  .components[]
  | select([.tiers[]] | index("full"))
  | select(.artifact == "magisk-module" and .name != "tagdrawer")
  | "payload/modules/" + (.zip | split("/") | last)
' "$MANIFEST")

TAG_PATH="$(jq -r '
  .components[] | select(.name=="tagdrawer") | "payload/modules/" + (.zip | split("/") | last)
' "$MANIFEST")"

mapfile -t APK_PATHS < <(jq -r '
  .components[]
  | select([.tiers[]] | index("full"))
  | select(.artifact == "user-apk" and (.apk // "") != "")
  | "payload/apks/" + (.apk | split("/") | last)
' "$MANIFEST")

# Full-tier user APKs bundled from pipeline/deploy/sources/ at stable wizard names.
while IFS=$'\t' read -r name asset; do
  [[ -n "$name" && -n "$asset" ]] || continue
  [[ -f "$SOURCES/$asset" ]] || continue
  wb="$(wizard_apk_basename "$name" "$MANIFEST")"
  [[ -n "$wb" ]] || wb="$(basename "$asset")"
  path="payload/apks/$wb"
  seen=0
  for p in "${APK_PATHS[@]}"; do
    [[ "$p" == "$path" ]] && { seen=1; break; }
  done
  [[ "$seen" -eq 0 ]] && APK_PATHS+=("$path")
done < <(jq -r '
  .components[]
  | select([.tiers[]] | index("full"))
  | select(.artifact == "user-apk" and (.apk // "") == "")
  | select((.external.asset // .incoming // "") != "")
  | [.name, (.external.asset // .incoming)] | @tsv
' "$MANIFEST")

SHERPA_JSON="$ROOT/pipeline/deploy/sherpa-models.json"
SHERPA_PATHS=()
if [[ -f "$SHERPA_JSON" ]]; then
  while IFS= read -r file; do
    [[ -n "$file" && -f "$SOURCES/$file" ]] || continue
    SHERPA_PATHS+=("payload/sherpa/$file")
  done < <(jq -r '.models[].file' "$SHERPA_JSON")
fi

REQUIRED=()
for p in "${MOD_PATHS[@]}"; do REQUIRED+=("$(basename "$p")"); done
REQUIRED+=("$(basename "$TAG_PATH")")
for p in "${APK_PATHS[@]}"; do REQUIRED+=("$(basename "$p")"); done

while IFS=$'\t' read -r name _pkg; do
  [[ -n "$name" ]] || continue
  inc="$(wizard_apk_basename "$name" "$MANIFEST")"
  [[ -n "$inc" ]] && REQUIRED+=("$inc")
done < <(jq -r '
  .components[]
  | select([.tiers[]] | index("full") or index("wizard"))
  | select(.artifact == "user-apk" and (.incoming // "") != "" and (.apk // "") == "")
  | [.name, .package] | @tsv
' "$MANIFEST")

declare -A _req_seen=()
_req_dedup=()
for r in "${REQUIRED[@]}"; do
  [[ -n "$r" ]] || continue
  [[ -n "${_req_seen[$r]+x}" ]] && continue
  _req_seen[$r]=1
  _req_dedup+=("$r")
done
REQUIRED=("${_req_dedup[@]}")

SHERPA_FILES=(
  "sherpa-onnx-streaming-zipformer-en-20M-2023-02-17-mobile.tar.bz2"
  "sherpa-onnx-nemo-fast-conformer-transducer-be-de-en-es-fr-hr-it-pl-ru-uk-20k-int8.tar.bz2"
)
for s in "${SHERPA_FILES[@]}"; do REQUIRED+=("$s"); done

jq -n \
  --argjson mod "$(printf '%s\n' "${MOD_PATHS[@]}" | jq -R . | jq -s .)" \
  --argjson apk "$(printf '%s\n' "${APK_PATHS[@]}" | jq -R . | jq -s .)" \
  --argjson sherpa "$(printf '%s\n' "${SHERPA_PATHS[@]}" | jq -R . | jq -s .)" \
  --arg td "$TAG_PATH" \
  --argjson req "$(printf '%s\n' "${REQUIRED[@]}" | jq -R . | jq -s .)" \
  '{
    "$comment": "Generated by pipeline/wizard/gen-pipeline-js.sh — do not hand-edit.",
    installerModulePaths: $mod,
    installerApkPaths: $apk,
    installerSherpaPaths: $sherpa,
    tagDrawerModulePath: $td,
    tagDrawerApkEntry: "system/app/PixelTagDrawer/PixelTagDrawer.apk",
    wallpaperPath: "payload/wallpaper/flip2-wallpaper.png",
    catalogRenames: {
      "forkgram": "forkgram.apk",
      "intertune": "intertune.apk",
      "bouncy": "bouncy.apk",
      "astro-loop": "astro-loop.apk",
      "materialfiles": "materialfiles.apk",
      "appshelf": "appshelf.apk",
      "fdroid-basic": "fdroid-basic.apk",
      "newpipe": "newpipe.apk",
      "vlc": "vlc.apk",
      "sherpa-en": "sherpa-onnx-streaming-zipformer-en-20M-2023-02-17-mobile.tar.bz2",
      "sherpa-uk": "sherpa-onnx-nemo-fast-conformer-transducer-be-de-en-es-fr-hr-it-pl-ru-uk-20k-int8.tar.bz2"
    },
    requiredIncoming: $req,
    requiredIncomingWithVoices: $req
  }' > "$OUT"

REQ_SLIM=()
for r in "${REQUIRED[@]}"; do
  skip=0
  for s in "${SHERPA_FILES[@]}"; do
    [[ "$r" == "$s" ]] && { skip=1; break; }
  done
  [[ "$skip" -eq 0 ]] && REQ_SLIM+=("$r")
done

jq -n \
  --argjson mod "$(printf '%s\n' "${MOD_PATHS[@]}" | jq -R . | jq -s .)" \
  --argjson apk "$(printf '%s\n' "${APK_PATHS[@]}" | jq -R . | jq -s .)" \
  --argjson sherpa '[]' \
  --arg td "$TAG_PATH" \
  --argjson req "$(printf '%s\n' "${REQ_SLIM[@]}" | jq -R . | jq -s .)" \
  '{
    "$comment": "Generated by pipeline/wizard/gen-pipeline-js.sh (slim — no bundled Sherpa).",
    installerCatalogId: "installer-slim",
    installerModulePaths: $mod,
    installerApkPaths: $apk,
    installerSherpaPaths: $sherpa,
    tagDrawerModulePath: $td,
    tagDrawerApkEntry: "system/app/PixelTagDrawer/PixelTagDrawer.apk",
    wallpaperPath: "payload/wallpaper/flip2-wallpaper.png",
    catalogRenames: {
      "forkgram": "forkgram.apk",
      "intertune": "intertune.apk",
      "bouncy": "bouncy.apk",
      "astro-loop": "astro-loop.apk",
      "materialfiles": "materialfiles.apk",
      "appshelf": "appshelf.apk",
      "fdroid-basic": "fdroid-basic.apk",
      "newpipe": "newpipe.apk",
      "vlc": "vlc.apk",
      "sherpa-en": "sherpa-onnx-streaming-zipformer-en-20M-2023-02-17-mobile.tar.bz2",
      "sherpa-uk": "sherpa-onnx-nemo-fast-conformer-transducer-be-de-en-es-fr-hr-it-pl-ru-uk-20k-int8.tar.bz2"
    },
    requiredIncoming: $req,
    requiredIncomingWithVoices: (
      $req + [
        "sherpa-onnx-streaming-zipformer-en-20M-2023-02-17-mobile.tar.bz2",
        "sherpa-onnx-nemo-fast-conformer-transducer-be-de-en-es-fr-hr-it-pl-ru-uk-20k-int8.tar.bz2"
      ]
    )
  }' > "$OUT_SLIM"

jq '. + {"installerCatalogId": "installer-full"}' "$OUT" > "${OUT}.tmp" && mv "${OUT}.tmp" "$OUT"
jq -c . "$OUT" | sed '1s/^/var PUSH_MANIFEST = /; s/$/;/' > "$JS_OUT"
jq -c . "$OUT_SLIM" | sed '1s/^/var PUSH_MANIFEST_SLIM = /; s/$/;/' > "$JS_OUT_SLIM"

echo "generated: $OUT"
echo "generated: $JS_OUT"
echo "generated: $OUT_SLIM"
echo "generated: $JS_OUT_SLIM"
